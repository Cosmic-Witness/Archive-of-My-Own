def g_eliza(name: str) -> str:
    """The figure Eliza.capm(plot=True) draws: returns scatter, dashed zero lines, fitted line."""
    r = Rng(seed_of(name))
    c = Canvas()
    cx, cy, half = SIZE / 2, SIZE / 2 + 2, SIZE / 2 - M
    c.line(cx, cy - half, cx, cy + half, WHITE, THIN, 0.35, "2.5 2.5")
    c.line(cx - half, cy, cx + half, cy, WHITE, THIN, 0.35, "2.5 2.5")
    beta = 1.3
    pts = []
    for _ in range(46):
        x = max(-1.0, min(1.0, r.normal(0, 0.42)))
        y = max(-1.05, min(1.05, beta * x * 0.62 + r.normal(0, 0.2)))
        pts.append((cx + x * half, cy - y * half))
    for k, (px, py) in enumerate(pts):
        if k % 4 == 0:                                            # a few residuals
            fit = cy - beta * 0.62 * (px - cx)
            c.line(px, py, px, fit, REDS[4], THIN, 0.9)
    for px, py in pts:
        c.circle(px, py, 1.5, WHITE, opacity=0.8, filled=True)
    xa, xb = -0.95, 0.95
    c.line(cx + xa * half, cy - beta * 0.62 * xa * half, cx + xb * half, cy - beta * 0.62 * xb * half, REDS[2], BOLD)
    return c.svg("schematic CAPM scatter, seeded from the name")


def g_ellie(name: str) -> str:
    """A contact sheet: one column per weekday, a frame per photo."""
    r = Rng(seed_of(name))
    c = Canvas()
    fw, fh, gx, gy = 17.0, 22.0, 6.0, 6.0
    cols = 5
    x0 = (SIZE - (cols * fw + (cols - 1) * gx)) / 2
    y0 = M + 4
    hi = (r.int(0, cols - 1), r.int(0, 2))
    for col in range(cols):
        rows = r.int(2, 4)
        x = x0 + col * (fw + gx)
        c.line(x, y0 - 7, x + fw, y0 - 7, ramp(col, cols), BASE)                  # the day's folder rule
        for row in range(rows):
            y = y0 + row * (fh + gy)
            col_c = WHITE if (col, row) == hi else ramp(col, cols)
            c.rect(x, y, fw, fh, col_c, BASE, rx=1.5)
            ridge = [(x + 2, y + fh - 5), (x + fw * 0.35, y + fh - 11 - r.random() * 4),
                     (x + fw * 0.6, y + fh - 7), (x + fw - 2, y + fh - 12 - r.random() * 3)]
            c.path(ridge, col_c, THIN, 0.9)
    return c.svg("a frame per photo, a column per day")


def g_ada(name: str) -> str:
    """Many videos in, one at a time out, with a gap that never shrinks."""
    c = Canvas()
    gate_x, mid = 72.0, SIZE / 2
    n_in = 5
    for i in range(n_in):
        y = M + 6 + i * 22.0
        col = ramp(i, n_in, reverse=True)
        c.rect(M, y - 5, 20, 10, col, BASE, rx=1.5)
        c.path([(M + 20, y), (gate_x - 10, mid)], col, THIN, 0.95)
    c.line(gate_x - 10, mid, gate_x + 6, mid, REDS[2], BASE)
    for dy in (-1, 1):                                                            # the gate
        c.line(gate_x, mid + dy * 5, gate_x, mid + dy * 24, WHITE, BASE)
    c.line(gate_x + 6, mid, SIZE - M, mid, REDS[2], BASE)
    xs = [92.0, 112.0, 132.0]
    for x in xs:
        c.rect(x - 4, mid - 4, 8, 8, WHITE, BASE, rx=1)
    for a, b in zip(xs, xs[1:]):                                                  # the minimum gap
        c.path([(a + 5, mid + 12), (a + 5, mid + 16), (b - 5, mid + 16), (b - 5, mid + 12)], WHITE, THIN, 0.55)
    return c.svg("videos queue, a gate spaces them out")


