#!/usr/bin/env python3
"""Draw the house-style SVG thumbnails in thumbs/.

One file per entry, named after the repo: thumbs/<name>.svg, 150 x 150, no text.

House style
  * one background, BG, everywhere;
  * line art in white plus a six-step ramp of reds, thin strokes, no fills to speak of;
  * a 16 px inner margin, so the CSS can round the corners without cutting anything.

Where it can, a thumbnail redraws something real from the project:
  Projections                        Figure 1 of the essay: the vector (3, 7) and its coordinates
  Naive-Discrete-Fourier-Transform   the toy signal and coefficient magnitudes from naive_dft_ish.py
                                     (recomputed here with the same formula)
  Stryder                            the 100 epoch losses printed in neural-obfuscation.ipynb
Eliza, Ellie and Ada have no data to plot, so they get drawings of what they do.
Any other repo name gets an abstract plot (fan, bundle, contour, scatter or rose) chosen by
hashing the name, so it never changes between builds.

Usage
    python scripts/thumbs.py                 # every entry in content/projects.yaml
    python scripts/thumbs.py --name MyRepo   # one name, even if it is not in the YAML yet
    python scripts/thumbs.py --force         # also overwrite files you drew by hand
    python scripts/thumbs.py --list          # show which style each name gets

Swapping in your own: save your SVG (or PNG) over thumbs/<name>.svg. Generated files start
with a marker comment; a file without it is treated as yours and left alone unless --force.
"""
