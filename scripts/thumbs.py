def g_stryder(name: str) -> str:
    c = Canvas()
    x0, x1, y0, y1 = M + 2, SIZE - M, M + 2, SIZE - M - 4        # plot box
    lo, hi = math.log10(0.003), math.log10(2.5)

    def X(e):
        return x0 + (x1 - x0) * (e - 1) / 99

    def Y(v):
        return y1 - (y1 - y0) * (math.log10(v) - lo) / (hi - lo)

    for decade in (1.0, 0.1, 0.01):                              # decade lines on the log axis
        c.line(x0, Y(decade), x1, Y(decade), WHITE, THIN, 0.14)
    c.line(x0, y0, x0, y1, WHITE, THIN, 0.5)
    c.line(x0, y1, x1, y1, WHITE, THIN, 0.5)
    for e in range(1, 101, 2):                                   # shading under the curve
        v = STRYDER_LOSS[e - 1]
        c.line(X(e), Y(v), X(e), y1, ramp(e, 100, reverse=True), THIN, 0.8)
    c.path([(X(e), Y(v)) for e, v in enumerate(STRYDER_LOSS, start=1)], WHITE, BASE + 0.25)
    c.circle(X(100), Y(STRYDER_LOSS[-1]), 2.0, WHITE, filled=True)
    return c.svg("epoch losses from neural-obfuscation.ipynb, log scale")


