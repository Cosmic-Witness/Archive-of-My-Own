# ---- tiny helpers -------------------------------------------------------------------------
def n(x: float) -> str:
    """Short number: at most one decimal, no trailing zeros."""
    s = f"{x:.1f}"
    s = s.rstrip("0").rstrip(".") if "." in s else s
    return "0" if s in ("-0", "") else s


def w(x: float) -> str:
    """Width or opacity: at most two decimals, no trailing zeros."""
    s = f"{x:.2f}".rstrip("0").rstrip(".")
    return s or "0"


def seed_of(name: str) -> int:
    return int.from_bytes(hashlib.sha256(name.encode("utf-8")).digest()[:8], "big")


class Rng:
    """SplitMix64. Own generator so the output never depends on the Python version."""
    MASK = (1 << 64) - 1

    def __init__(self, seed: int):
        self.s = seed & self.MASK

    def _next(self) -> int:
        self.s = (self.s + 0x9E3779B97F4A7C15) & self.MASK
        z = self.s
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & self.MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & self.MASK
        return z ^ (z >> 31)

    def random(self) -> float:
        return (self._next() >> 11) / float(1 << 53)

    def uniform(self, a: float, b: float) -> float:
        return a + (b - a) * self.random()

    def normal(self, mu: float = 0.0, sigma: float = 1.0) -> float:
        u1 = max(self.random(), 1e-12)
        return mu + sigma * math.sqrt(-2.0 * math.log(u1)) * math.cos(2 * math.pi * self.random())

    def int(self, a: int, b: int) -> int:
        return a + self._next() % (b - a + 1)

    def choice(self, seq):
        return seq[self._next() % len(seq)]


class Canvas:
    def __init__(self) -> None:
        self.parts: list[str] = []

    def add(self, s: str) -> None:
        self.parts.append(s)

    def path(self, pts, color=WHITE, width=BASE, opacity=1.0, dash=None, close=False, fill="none") -> None:
        if len(pts) < 2:
            return
        d = "M" + " ".join(f"{n(x)} {n(y)}" for x, y in pts) + ("Z" if close else "")
        self.add(f'<path d="{d}"{self._style(color, width, opacity, dash, fill)}/>')

    def line(self, x1, y1, x2, y2, color=WHITE, width=BASE, opacity=1.0, dash=None) -> None:
        self.path([(x1, y1), (x2, y2)], color, width, opacity, dash)

    def circle(self, cx, cy, r, color=WHITE, width=BASE, opacity=1.0, filled=False) -> None:
        if filled:
            self.add(f'<circle cx="{n(cx)}" cy="{n(cy)}" r="{n(r)}" fill="{color}"{self._op(opacity)} stroke="none"/>')
        else:
            self.add(f'<circle cx="{n(cx)}" cy="{n(cy)}" r="{n(r)}"{self._style(color, width, opacity, None, "none")}/>')

    def rect(self, x, y, w, h, color=WHITE, width=BASE, opacity=1.0, rx=0.0) -> None:
        r = f' rx="{n(rx)}"' if rx else ""
        self.add(f'<rect x="{n(x)}" y="{n(y)}" width="{n(w)}" height="{n(h)}"{r}{self._style(color, width, opacity, None, "none")}/>')

    @staticmethod
    def _op(opacity: float) -> str:
        return "" if opacity >= 1 else f' fill-opacity="{w(opacity)}"'

    @staticmethod
    def _style(color, width, opacity, dash, fill) -> str:
        s = f' fill="{fill}" stroke="{color}" stroke-width="{w(width)}"'
        if opacity < 1:
            s += f' stroke-opacity="{w(opacity)}"'
        if dash:
            s += f' stroke-dasharray="{dash}"'
        return s

    def svg(self, note: str = "") -> str:
        body = "\n".join(self.parts)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" width="{SIZE}" height="{SIZE}">\n'
                f'<!-- {MARK}{(" | " + note) if note else ""} -->\n'
                f'<rect width="{SIZE}" height="{SIZE}" fill="{BG}"/>\n'
                f'<g stroke-linecap="round" stroke-linejoin="round">\n{body}\n</g>\n</svg>\n')


def ramp(i: int, count: int, reverse: bool = False) -> str:
    """Pick a red from the ramp for position i of count (0 = lightest unless reverse)."""
    t = i / max(count - 1, 1)
    if reverse:
        t = 1 - t
    return REDS[min(int(round(t * (len(REDS) - 1))), len(REDS) - 1)]


def arrow_head(c: Canvas, x, y, ang, size=6.0, color=WHITE, width=BASE, spread=0.45) -> None:
    for s in (-1, 1):
        a = ang + math.pi + s * spread
        c.line(x, y, x + size * math.cos(a), y + size * math.sin(a), color, width)


def frame_grid(c: Canvas, x0, y0, x1, y1, nx, ny, opacity=0.10) -> None:
    for i in range(nx + 1):
        x = x0 + (x1 - x0) * i / nx
        c.line(x, y0, x, y1, WHITE, THIN, opacity)
    for j in range(ny + 1):
        y = y0 + (y1 - y0) * j / ny
        c.line(x0, y, x1, y, WHITE, THIN, opacity)


# ---- marching squares ---------------------------------------------------------------------
_CASES = {1: [("L", "B")], 2: [("B", "R")], 3: [("L", "R")], 4: [("T", "R")], 5: [("T", "L"), ("B", "R")],
          6: [("T", "B")], 7: [("T", "L")], 8: [("T", "L")], 9: [("T", "B")], 10: [("T", "R"), ("L", "B")],
          11: [("T", "R")], 12: [("L", "R")], 13: [("B", "R")], 14: [("L", "B")]}


def contour_segments(f, x0, y0, x1, y1, nx, ny, level):
    xs = [x0 + (x1 - x0) * i / nx for i in range(nx + 1)]
    ys = [y0 + (y1 - y0) * j / ny for j in range(ny + 1)]
    v = [[f(x, y) for x in xs] for y in ys]
    segs = []

    def cross(p, q, a, b):
        t = (level - a) / (b - a) if b != a else 0.5
        return (p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1]))

    for j in range(ny):
        for i in range(nx):
            tl, tr, br, bl = (xs[i], ys[j]), (xs[i + 1], ys[j]), (xs[i + 1], ys[j + 1]), (xs[i], ys[j + 1])
            vtl, vtr, vbr, vbl = v[j][i], v[j][i + 1], v[j + 1][i + 1], v[j + 1][i]
            idx = (vtl > level) * 8 + (vtr > level) * 4 + (vbr > level) * 2 + (vbl > level) * 1
            if idx in (0, 15):
                continue
            e = {"T": cross(tl, tr, vtl, vtr), "R": cross(tr, br, vtr, vbr),
                 "B": cross(bl, br, vbl, vbr), "L": cross(tl, bl, vtl, vbl)}
            for a, b in _CASES[idx]:
                segs.append((e[a], e[b]))
    return segs


def chain(segs):
    key = lambda p: (round(p[0], 2), round(p[1], 2))
    ends: dict = {}
    for i, (a, b) in enumerate(segs):
        ends.setdefault(key(a), []).append(i)
        ends.setdefault(key(b), []).append(i)
    used = [False] * len(segs)
    out = []
    for i in range(len(segs)):
        if used[i]:
            continue
        used[i] = True
        line = [segs[i][0], segs[i][1]]
        for head in (False, True):
            while True:
                tip = key(line[0] if head else line[-1])
                nxt = next((j for j in ends.get(tip, []) if not used[j]), None)
                if nxt is None:
                    break
                used[nxt] = True
                p, q = segs[nxt]
                other = q if key(p) == tip else p
                line.insert(0, other) if head else line.append(other)
        out.append(line)
    return out


