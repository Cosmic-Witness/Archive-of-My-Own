def a_fan(name: str) -> str:
    r = Rng(seed_of(name))
    c = Canvas()
    px, py = r.uniform(62, 90), r.uniform(70, 96)
    count = r.int(11, 16)
    base_ang = r.uniform(-1.2, -0.4)
    for i in range(count):
        a = base_ang - i * (r.uniform(1.0, 1.5) / count)
        L = 170
        c.line(px, py, px + L * math.cos(a), py + L * math.sin(a), ramp(i, count), THIN + 0.15, 0.9)
    for i in range(3):
        a = base_ang - 0.18 - i * 0.35
        c.line(px, py, px - 170 * math.cos(a) * 0.5, py - 170 * math.sin(a) * 0.5, REDS[4], THIN, 0.8)
    c.line(M - 6, py + 30, SIZE - M + 6, py + 30, WHITE, BASE, 0.9)
    c.line(px, M - 6, px, SIZE - M + 6, WHITE, BASE, 0.9, "2 3")
    c.circle(px, py, 2, WHITE, filled=True)
    return c.svg("fan")


def a_bundle(name: str) -> str:
    r = Rng(seed_of(name))
    c = Canvas()
    (f1, p1), (f2, p2) = (r.uniform(0.8, 1.6), r.uniform(0, 6.28)), (r.uniform(2.0, 3.4), r.uniform(0, 6.28))

    def centre(t: float) -> float:
        return 0.9 * math.sin(f1 * math.pi * t * 2 + p1) * (1 - 0.35 * t) + 0.25 * math.sin(f2 * math.pi * t * 2 + p2)

    cnt = 13
    x0, x1 = M - 4, SIZE - M + 4
    for i in range(cnt):
        spread = (i - cnt / 2) / cnt
        pts = [(x0 + (x1 - x0) * k / 60, SIZE / 2 - 26 * (centre(k / 60) + spread * 1.6 * k / 60)) for k in range(61)]
        c.path(pts, ramp(abs(i - cnt // 2), cnt // 2 + 1, reverse=True), THIN + 0.1, 0.95)
    c.path([(x0 + (x1 - x0) * k / 60, SIZE / 2 - 26 * centre(k / 60)) for k in range(61)], WHITE, BASE + 0.2)
    return c.svg("bundle")


