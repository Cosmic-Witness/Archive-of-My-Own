def _ndft_data():
    """Same signal and probe as naive_dft_ish.py: 10,000 samples on [0, 1], n = 1..10."""
    N = 10000
    t = [i / (N - 1) for i in range(N)]
    two_pi = 2 * math.pi

    def f(x):
        return (3 * math.cos(two_pi * x) + 12 * math.cos(two_pi * 2 * x) - 0.8 * math.sin(two_pi * 3 * x)
                + 15 * math.cos(two_pi * x * 5) + 100 * math.sin(two_pi * 7 * x))

    vals = [f(x) for x in t]
    mags = []
    for k in range(1, 11):
        re = im = 0.0
        prev = None
        for x, fx in zip(t, vals):
            a, b = fx * math.cos(two_pi * k * x), -fx * math.sin(two_pi * k * x)     # f * exp(-2 pi i k t)
            if prev is not None:
                dx = x - prev[0]
                re += 0.5 * (a + prev[1]) * dx
                im += 0.5 * (b + prev[2]) * dx
            prev = (x, a, b)
        mags.append(2 * math.hypot(re, im))
    return f, mags


def g_ndft(name: str) -> str:
    f, mags = _ndft_data()
    c = Canvas()
    x0, x1 = M, SIZE - M
    top_mid, amp = 46.0, 27.0
    c.line(x0, top_mid, x1, top_mid, WHITE, THIN, 0.18)
    pts = [(x0 + (x1 - x0) * i / 239, top_mid - amp * f(i / 239) / 131.0) for i in range(240)]
    c.path(pts, WHITE, BASE, 0.95)
    base, tall = 128.0, 50.0
    c.line(x0, base, x1, base, WHITE, THIN, 0.45)
    peak = max(mags)
    for k, m in enumerate(mags, start=1):
        x = x0 + (x1 - x0) * (k - 0.5) / 10
        h = tall * m / peak
        col = WHITE if m == peak else ramp(k, 11)
        if h > 0.4:
            c.line(x, base, x, base - h, col, BASE)
        c.circle(x, base - h, 1.9 if m == peak else 1.5, col, filled=m == peak)
    return c.svg("signal and magnitudes recomputed from naive_dft_ish.py")


