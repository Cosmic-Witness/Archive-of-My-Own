def style_of(name: str) -> str:
    key = name.lower()
    if key in BESPOKE:
        return "bespoke"
    return sorted(ABSTRACT)[seed_of(name) % len(ABSTRACT)]


def render(name: str) -> str:
    key = name.lower()
    if key in BESPOKE:
        return BESPOKE[key][0](name)
    return ABSTRACT[style_of(name)](name)


def describe(name: str) -> str:
    """Default alt text for a thumbnail, used by build.py when the YAML has none."""
    key = name.lower()
    if key in BESPOKE:
        return BESPOKE[key][1]
    return ABSTRACT_ALT[style_of(name)]


