def entry_names() -> list[str]:
    try:
        from ruamel.yaml import YAML
    except ImportError:
        sys.exit("ruamel.yaml is needed to read content/projects.yaml (pip install -r requirements.txt), or use --name")
    if not CONTENT.exists():
        return []
    data = YAML().load(CONTENT.read_text(encoding="utf-8")) or {}
    return [str(e.get("id") or (e.get("github") or {}).get("name")) for e in data.get("entries", []) or []
            if not e.get("hidden")]


def write(path: pathlib.Path, text: str, force: bool) -> str:
    if path.exists() and not force and MARK not in path.read_text(encoding="utf-8", errors="ignore")[:400]:
        return "kept (not generated by this script)"
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return "unchanged"
    path.write_text(text, encoding="utf-8")
    return "written"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", action="append", help="draw this name (repeatable); default is every entry in the YAML")
    ap.add_argument("--force", action="store_true", help="overwrite files that this script did not generate")
    ap.add_argument("--list", action="store_true", help="show the style chosen for each name and exit")
    args = ap.parse_args()

    names = list(dict.fromkeys((args.name or entry_names()) + ["photo-placeholder"]))
    if args.list:
        for nm in names:
            print(f"{nm:40s} {style_of(nm)}")
        return
    THUMBS.mkdir(exist_ok=True)
    for nm in names:
        print(f"thumbs/{nm}.svg: {write(THUMBS / (nm + '.svg'), render(nm), args.force)}")
    print(f"favicon.svg: {write(ROOT / 'favicon.svg', favicon(True), args.force)}")


if __name__ == "__main__":
    main()
